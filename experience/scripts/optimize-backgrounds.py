"""Lossless backup originals stay untouched. High-quality WebP encoding only.
No resize, crop, colour grading, or semantic image editing.
"""
from PIL import Image
from pathlib import Path
import numpy as np,json,math,shutil,subprocess,os,hashlib
out=Path('src/assets/backgrounds');out.mkdir(parents=True,exist_ok=True)
def quality(a,b):
 a=np.asarray(a.convert('RGB'),dtype=np.float64);b=np.asarray(b.convert('RGB'),dtype=np.float64)
 mse=np.mean((a-b)**2);psnr=10*math.log10(255**2/mse) if mse else 100.
 ya=a@np.array([.299,.587,.114]);yb=b@np.array([.299,.587,.114]);h,w=ya.shape;h=h//8*8;w=w//8*8
 x=ya[:h,:w].reshape(h//8,8,w//8,8).transpose(0,2,1,3).reshape(-1,64);y=yb[:h,:w].reshape(h//8,8,w//8,8).transpose(0,2,1,3).reshape(-1,64)
 ux=x.mean(1);uy=y.mean(1);vx=x.var(1);vy=y.var(1);cov=((x-ux[:,None])*(y-uy[:,None])).mean(1)
 ssim=np.mean(((2*ux*uy+6.5025)*(2*cov+58.5225))/((ux**2+uy**2+6.5025)*(vx+vy+58.5225)))
 return {'psnrDb':round(psnr,3),'block8LumaSSIM':round(float(ssim),6)}
report=[]
cwebp=os.environ.get('FLOW_CWEBP') or shutil.which('cwebp')
for n in range(1,8):
 for kind in ['clean','artwork']:
  source=Path(f'public/scenes/page{n:02}-reference-clean.jpg') if kind=='clean' else next(p for p in Path('references').glob('*.png') if f'{n:02}' in p.name)
  original=Image.open(source);im=original.convert('RGB');dest=out/f'page{n:02}-{kind}.webp'
  if n==6 and kind=='clean':
   dest=out/'page06-clean.jpg';shutil.copyfile(source,dest);q=quality(im,im);encoding='original JPEG (mirror source byte-identical)'
  elif kind=='artwork':
   if cwebp:
    for level in [60,80,100]:
     subprocess.run([cwebp,'-quiet','-near_lossless',str(level),'-q','100','-m','6','-metadata','icc',str(source),'-o',str(dest)],check=True)
     q=quality(im,Image.open(dest))
     if q['psnrDb']>=49 and q['block8LumaSSIM']>=.9975:break
    encoding=f'WebP near-lossless {level}'
   else:
    im.save(dest,'WEBP',lossless=True,method=6,exact=True,icc_profile=original.info.get('icc_profile',b''));q=quality(im,Image.open(dest));encoding='WebP lossless'
  else:
   for level in [94,96,98]:
    im.save(dest,'WEBP',quality=level,method=6,exact=True,icc_profile=original.info.get('icc_profile',b''));q=quality(im,Image.open(dest))
    if q['psnrDb']>=43 and q['block8LumaSSIM']>=.990:break
   encoding=f'WebP {level}'
   if q['psnrDb']<43 or q['block8LumaSSIM']<.990 or dest.stat().st_size>=source.stat().st_size*.95:
    dest.unlink();dest=out/f'page{n:02}-clean.jpg';shutil.copyfile(source,dest);q=quality(im,im);encoding='original optimized JPEG (smaller than high-quality WebP)'
  assert Image.open(dest).size==im.size
  report.append({'page':n,'kind':kind,'original':str(source),'asset':str(dest),'width':im.width,'height':im.height,'originalBytes':source.stat().st_size,'optimizedBytes':dest.stat().st_size,'originalSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'encoding':encoding,**q})
  print(n,kind,source.stat().st_size,'->',dest.stat().st_size,encoding,q,flush=True)
Path('artifacts/background-loading/asset-quality.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
lines=["import type {Page} from './session';","/** Generated by scripts/optimize-backgrounds.py. Vite fingerprints each URL. */","export const backgroundAssets:Record<Page,{plate:string;artwork?:string}>={"]
for n in range(1,8):
 plate=next(r for r in report if r['page']==n and r['kind']=='clean');art=next(r for r in report if r['page']==n and r['kind']=='artwork')
 row=f" {n}:{{plate:new URL('./assets/backgrounds/{Path(plate['asset']).name}',import.meta.url).href"
 if n>1:row+=f",artwork:new URL('./assets/backgrounds/{Path(art['asset']).name}',import.meta.url).href"
 lines.append(row+'},')
lines.append('};');Path('src/backgroundAssets.ts').write_text('\n'.join(lines)+'\n')
